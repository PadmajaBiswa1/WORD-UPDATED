import { useEditorStore } from '@/store';

export function exportPageFill(design = {}) {
  return design.pageColorMode === 'custom' && design.pageColor ? design.pageColor : '#ffffff';
}

export function portableExportHtml(html, { design = {} } = {}) {
  const root = document.createElement('div');
  root.innerHTML = html || '<p></p>';
  const gold = design.accent || '#c9a84c';
  const themes = {
    'table-theme-grid': { header: '#393939', ink: '#ffffff', border: '#666666' },
    'table-theme-accent': { header: gold, ink: '#000000', border: gold, stripe: '#fcf8ed' },
    'table-theme-dark-header': { header: '#18181b', ink: '#fafafa', border: '#27272a', stripe: '#eeeeee' },
    'table-theme-striped': { header: '#f4eddb', ink: gold, border: '#888888', stripe: '#f5f5f5' },
    'table-theme-minimalist': { header: 'transparent', border: '#999999' },
  };
  root.querySelectorAll('table').forEach((table) => {
    const theme = themes[table.dataset.theme] || Object.entries(themes).find(([name]) => table.classList.contains(name))?.[1];
    for (const [index, row] of Array.from(table.rows).entries()) for (const cell of Array.from(row.cells)) {
      if (!cell.style.border) cell.style.border = `1px solid ${theme?.border || '#d0d0d0'}`;
      if (!cell.style.padding) cell.style.padding = '7px 12px';
      if (!cell.style.backgroundColor && (cell.tagName === 'TH' || (theme?.stripe && index % 2 === 1))) cell.style.backgroundColor = cell.tagName === 'TH' ? (theme?.header || '#f7f7f7') : theme.stripe;
      if (!cell.style.color && cell.tagName === 'TH' && theme?.ink) cell.style.color = theme.ink;
    }
  });
  // Capture styles generated by the active editor's theme as literal CSS, so
  // an external application does not need EtherX's stylesheet or CSS variables.
  const editor = useEditorStore.getState().editor;
  const live = document.querySelector('#editor-scroll-area .ProseMirror');
  if (live && editor && editor.getHTML() === html) {
    for (const tag of ['p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'span', 'th', 'td', 'table', 'img', 'blockquote', 'pre']) {
      const nodes = root.querySelectorAll(tag);
      const originals = live.querySelectorAll(tag);
      nodes.forEach((node, index) => {
        if (!originals[index]) return;
        const computed = getComputedStyle(originals[index]);
        const properties = ['color', 'font-family', 'font-size', 'font-weight', 'font-style', 'line-height', 'text-align', 'background-color', 'vertical-align'];
        if (['TD', 'TH', 'TABLE'].includes(node.tagName)) properties.push('border-top', 'border-right', 'border-bottom', 'border-left', 'padding-top', 'padding-bottom', 'padding-left', 'padding-right');
        for (const property of properties) if (computed.getPropertyValue(property) && !originals[index].style.getPropertyValue(property)) node.style.setProperty(property, computed.getPropertyValue(property));
      });
    }
  }
  const resolveVariables = (value) => value.replace(/var\(--gold(?:,[^)]+)?\)/g, gold).replace(/var\(--(?:text-primary|text-doc|design-subtle)(?:,[^)]+)?\)/g, '#1a1a1a').replace(/var\(--border(?:,[^)]+)?\)/g, '#888888');
  root.querySelectorAll('[style]').forEach((node) => node.setAttribute('style', resolveVariables(node.getAttribute('style'))));
  root.querySelectorAll('img').forEach((img) => {
    for (const dimension of ['width', 'height']) if (!img.style[dimension] && img.hasAttribute(dimension)) img.style[dimension] = /^\d+(\.\d+)?$/.test(img.getAttribute(dimension)) ? `${img.getAttribute(dimension)}px` : img.getAttribute(dimension);
  });
  return root.innerHTML;
}

export function flattenExportMedia(root) {
  root.querySelectorAll('iframe').forEach((frame) => {
    const src = frame.getAttribute('src');
    const paragraph = document.createElement('p');
    const link = document.createElement('a');
    link.href = src || '';
    link.textContent = `${src?.includes('sketchfab') ? '3D model' : 'Online video'}: ${src || 'Unavailable source'}`;
    paragraph.appendChild(link);
    frame.replaceWith(paragraph);
  });
}

export function loadExportImage(src) {
  return new Promise((resolve, reject) => {
    const img = new window.Image();
    const timer = setTimeout(() => reject(new Error('An image could not be loaded for export')), 15000);
    img.onload = () => { clearTimeout(timer); resolve(img); };
    img.onerror = () => { clearTimeout(timer); reject(new Error('An image could not be loaded for export')); };
    if (!src.startsWith('data:') && !src.startsWith('blob:')) img.crossOrigin = 'anonymous';
    img.src = src;
  });
}

export async function rasterizeExportImage(src, { filter, opacity, width, height } = {}) {
  const image = await loadExportImage(src);
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, Math.round(width || image.naturalWidth || 300));
  canvas.height = Math.max(1, Math.round(height || image.naturalHeight || 200));
  const ctx = canvas.getContext('2d');
  if (filter) ctx.filter = filter;
  if (opacity != null && opacity !== '') ctx.globalAlpha = Number(opacity);
  ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
  return { src: canvas.toDataURL('image/png'), width: canvas.width, height: canvas.height };
}
